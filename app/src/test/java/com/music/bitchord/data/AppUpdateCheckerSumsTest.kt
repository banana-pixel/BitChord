package com.music.bitchord.data

import com.music.bitchord.BuildConfig
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * The update manifest is the only thing standing between a compromised
 * release asset and code running as this app, so the parser is tested for
 * what it accepts as much as for what it refuses.
 */
class AppUpdateCheckerSumsTest {

    private val hash = "a".repeat(64)
    private val otherHash = "b".repeat(64)
    private val apk = "BitChord-v1.8.1.apk"

    private fun parse(body: String, name: String = apk) =
        AppUpdateChecker.parseSumsEntry(body, name)

    @Test
    fun `text mode line with two spaces is accepted`() {
        assertEquals(hash, parse("$hash  $apk\n"))
    }

    @Test
    fun `binary mode line with an asterisk marker is accepted`() {
        assertEquals(hash, parse("$hash *$apk\n"))
    }

    @Test
    fun `CRLF manifests are accepted`() {
        assertEquals(hash, parse("$hash  $apk\r\n"))
    }

    @Test
    fun `uppercase digests are lowercased`() {
        assertEquals(hash, parse("${"A".repeat(64)}  $apk\n"))
    }

    @Test
    fun `the right file is picked out of a multi-entry manifest`() {
        val body = """
            ${"c".repeat(64)}  BitChord-v1.8.0.apk
            $hash  $apk
            ${"d".repeat(64)}  BitChordTV-v1.8.1.apk
        """.trimIndent()
        assertEquals(hash, parse(body))
    }

    @Test
    fun `a TV entry never satisfies a phone lookup`() {
        val body = "$hash  BitChordTV-v1.8.1.apk\n"
        assertNull(parse(body))
        assertEquals(hash, parse(body, "BitChordTV-v1.8.1.apk"))
    }

    @Test
    fun `a prefix of the file name is not a match`() {
        assertNull(parse("$hash  BitChord-v1.8.1.apk.sig\n"))
        assertNull(parse("$hash  BitChord-v1.8.apk\n"))
    }

    @Test
    fun `a missing entry yields null`() {
        assertNull(parse("$hash  BitChord-v1.8.0.apk\n"))
        assertNull(parse(""))
    }

    @Test
    fun `a repeated name with one digest is fine`() {
        assertEquals(hash, parse("$hash  $apk\n$hash  $apk\n"))
    }

    @Test
    fun `a repeated name with conflicting digests is refused`() {
        assertNull(parse("$hash  $apk\n$otherHash  $apk\n"))
    }

    @Test
    fun `a long hex string cannot lend its tail to a file name`() {
        // 128 hex chars followed by the real name: if the pattern were not
        // anchored, the second half could be read as this file's digest.
        val body = "${"e".repeat(128)}  $apk\n"
        assertNull(parse(body))
    }

    @Test
    fun `short and non-hex digests are refused`() {
        assertNull(parse("${"a".repeat(63)}  $apk\n"))
        assertNull(parse("${"a".repeat(64)}z  $apk\n"))
    }

    @Test
    fun `comments and blank lines are ignored`() {
        val body = "# generated by CI\n\n$hash  $apk\n\n"
        assertEquals(hash, parse(body))
    }

    @Test
    fun `an entry is not read out of the middle of a line`() {
        assertNull(parse("junk $hash  $apk\n"))
    }

    @Test
    fun `shaSumsUrl only accepts this flavour's uploaded manifest`() {
        val prefix = BuildConfig.UPDATE_APK_PREFIX
        val release = releaseWith(
            asset("${prefix}SHA256SUMS.txt", "https://example.test/sums", "uploaded"),
            asset("BitChordTV-SHA256SUMS.txt", "https://example.test/tv-sums", "uploaded"),
            asset("${prefix}v1.8.1.apk", "https://example.test/apk", "uploaded"),
        )
        assertEquals("https://example.test/sums", AppUpdateChecker.shaSumsUrl(release))
    }

    @Test
    fun `shaSumsUrl refuses a manifest that is not uploaded yet`() {
        val prefix = BuildConfig.UPDATE_APK_PREFIX
        val release = releaseWith(
            asset("${prefix}SHA256SUMS.txt", "https://example.test/sums", "new"),
        )
        assertNull(AppUpdateChecker.shaSumsUrl(release))
    }

    @Test
    fun `shaSumsUrl is null when the release ships no manifest`() {
        val release = releaseWith(
            asset("${BuildConfig.UPDATE_APK_PREFIX}v1.8.1.apk", "https://example.test/apk", "uploaded"),
        )
        assertNull(AppUpdateChecker.shaSumsUrl(release))
    }

    private fun asset(name: String, url: String, state: String) = """
        {"name":"$name","browser_download_url":"$url","state":"$state"}
    """.trimIndent()

    private fun releaseWith(vararg assets: String): JsonObject =
        Json.parseToJsonElement(
            """{"assets":[${assets.joinToString(",")}]}""",
        ) as JsonObject
}
